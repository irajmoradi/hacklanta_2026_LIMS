import { test, expect } from '@playwright/test';
import { useDemoSeat } from './demoSeat';
useDemoSeat();
test('shared reading shelf, completion, reaction, archive and responsive layout', async ({page}) => {
  await page.goto('/');
  await page.getByRole('button', {name:'Reading list', exact:true}).click();
  const dialog = page.getByRole('dialog', {name:'Reading list', exact:true});
  await expect(dialog).toContainText('waiting for its first story');
  await dialog.getByLabel('Title', {exact:true}).fill('The Creative Act');
  await dialog.getByLabel('Author (optional)').fill('Rick Rubin');
  await dialog.getByLabel('Why read it? (optional)').fill('Make space for a daily creative practice.');
  await dialog.getByRole('button', {name:'Add reading', exact:true}).click();
  await dialog.getByLabel('One-line takeaway (optional)').fill('Pay attention to the ordinary.');
  await dialog.getByRole('button', {name:/Mark as read/}).click();
  await expect(dialog).toContainText('+5 XP / 5 coins earned');
  await dialog.getByRole('button', {name:'Add reaction', exact:true}).click();
  await dialog.getByRole('button', {name:'React 🔥', exact:true}).click();
  await expect(dialog.getByRole('button', {name:'React 🔥', exact:true})).toHaveAttribute('aria-pressed','true');
  await page.screenshot({path:'artifacts/feat020/desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/feat020/mobile.png'});
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await dialog.getByRole('button', {name:'Previous week', exact:true}).click();
  await expect(dialog).toContainText('Archived shelf');
  await expect(dialog.getByRole('button', {name:'Add reading', exact:true})).toHaveCount(0);
  await dialog.getByRole('button', {name:'Next week', exact:true}).click();
  await expect(dialog).toContainText('The Creative Act');
  await dialog.getByRole('button', {name:'Suggest reading', exact:true}).click();
  await dialog.getByRole('button', {name:/Atomic Habits/}).click();
  await expect(dialog.getByLabel('Title', {exact:true})).toHaveValue('Atomic Habits');
});
