test('arena renderer timing and full-screen transition',async({page},info)=>{
  test.skip(info.project.name!=='mock');
  await page.goto('/');await page.getByRole('button',{name:'Compete',exact:true}).click();
  await page.getByRole('button',{name:/The seven-day sprint/}).click();
  await expect(page.getByRole('button',{name:'Inspect Lance',exact:true})).toBeVisible();
  await page.waitForTimeout(1200);
  const stats=await page.evaluate(async()=>{
    const dialog=document.querySelector<HTMLDialogElement>('.arena-modal')!,canvas=dialog.querySelector('canvas')!;
    const gl=canvas.getContext('webgl2')!,ext=gl.getExtension('WEBGL_debug_renderer_info');
    const frames:number[]=[];let previous=performance.now();
    await new Promise<void>(resolve=>{const sample=(now:number)=>{frames.push(now-previous);previous=now;if(frames.length<120)requestAnimationFrame(sample);else resolve();};requestAnimationFrame(sample);});
    frames.shift();frames.sort((a,b)=>a-b);
    return {renderer:ext?String(gl.getParameter(ext.UNMASKED_RENDERER_WEBGL)):'unknown',medianFrameMs:frames[Math.floor(frames.length/2)],p95FrameMs:frames[Math.floor(frames.length*.95)],animationMs:parseFloat(getComputedStyle(dialog).animationDuration)*1000,width:dialog.getBoundingClientRect().width,height:dialog.getBoundingClientRect().height,viewport:[innerWidth,innerHeight]};
  });
  expect(stats.animationMs).toBeLessThanOrEqual(300);expect(stats.width).toBe(stats.viewport[0]);expect(stats.height).toBe(stats.viewport[1]);
  await mkdir('test-results',{recursive:true});await writeFile('test-results/colosseum-performance.json',JSON.stringify(stats,null,2));
});

