import { expect, test } from '@playwright/test';
import { useDemoSeat } from './demoSeat';
useDemoSeat();
for (const width of [1440, 390]) test(`decluttered navigation at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(() => localStorage.setItem('village:dashboard:11111111-1111-4111-8111-111111111111:00000000-0000-4000-8000-000000000001', JSON.stringify({ order: ['mayor','gazette','corner','feed','goal'], hidden: ['gazette'] })));
  await page.goto('/');
  const dashboard = page.getByRole('complementary', { name: 'Village dashboard' });
  await expect(dashboard.getByRole('button', { name: 'Accomplishments', exact: true })).toBeVisible();
  await expect(dashboard.getByRole('button', { name: 'Friends', exact: true })).toHaveCount(0);
  await expect(dashboard.locator('[data-widget="mayor"], [data-widget="gazette"]')).toHaveCount(0);
  await expect(dashboard.getByText('Hidden widgets (1)', { exact: true })).toHaveCount(0);
  const friends = page.getByRole('button', { name: 'Friends', exact: true });
  const hall = page.getByRole('button', { name: 'Community Hall', exact: true });
  await expect(friends).toBeVisible();
  const f = (await friends.boundingBox())!, h = (await hall.boundingBox())!;
  expect(Math.abs(f.x + f.width - h.x - h.width)).toBeLessThan(1);
  expect(h.y - f.y - f.height).toBeCloseTo(8, 0);
  expect(h.y + h.height).toBeLessThan(900);
  if (width === 390) {
    const d = (await dashboard.boundingBox())!;
    expect(d.y + d.height).toBeLessThanOrEqual(f.y);
  }
  await page.screenshot({ path: `artifacts/web052/dashboard-${width}.png` });
  await friends.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog', { name: 'Friends', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await friends.evaluate(el => el.blur());
  await page.keyboard.press('b');
  await expect(page.getByRole('dialog', { name: 'Friends', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Village', exact: true }).click();
  await page.getByRole('button', { name: 'Read the Village Gazette', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'The Village Gazette', exact: true })).toBeVisible();
  await expect(page.getByLabel('Past issues')).toBeVisible();
  await page.screenshot({ path: `artifacts/web052/gazette-${width}.png` });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Mayor', exact: true }).click();
  await page.keyboard.press('1');
  const updates = page.getByRole('region', { name: 'Mayor updates', exact: true });
  await expect(updates).toBeVisible();
  await expect(updates).toContainText('Available Mayor history');
  await expect(updates.locator('article').first()).toBeVisible();
  await page.screenshot({ path: `artifacts/web052/mayor-${width}.png` });
  expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: /What's new/ })).toBeFocused();
});
