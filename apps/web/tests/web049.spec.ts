import {test, expect} from '@playwright/test';
import {useDemoSeat} from './demoSeat';
useDemoSeat();
for (const width of [1440,390]) test(`house history and leave protection at ${width}px`, async ({page,context}) => {
  await page.setViewportSize({width,height:1000});
  await page.goto('/');
  await page.getByRole('button',{name:'My profile',exact:true}).click();
  await page.getByRole('tab',{name:'House',exact:true}).click();
  await page.getByRole('button',{name:'Edit my house',exact:true}).click();
  const editor = page.getByRole('region',{name:'House editor'});
  const preview = page.getByLabel('Rotating house preview');
  const original = await preview.getAttribute('data-colors');
  await expect(editor.getByRole('button',{name:'Undo',exact:true})).toBeDisabled();
  await editor.getByRole('button',{name:'Paint wall #487d6b'}).click();
  await expect(preview).toHaveAttribute('data-colors', /"wall":"#487d6b"/);
  await expect(editor.getByText('Unsaved changes (1)',{exact:true})).toBeVisible();
  if (width === 1440) {
    const villages = page.getByRole('combobox',{name:'Village',exact:true,includeHidden:true});
    const before = await villages.inputValue();
    await villages.dispatchEvent('focusin');
    await villages.evaluate((el:HTMLSelectElement) => {el.value = [...el.options].find(o=>o.label==='Join with invite code')!.value; el.dispatchEvent(new Event('change',{bubbles:true}));});
    await page.getByRole('dialog',{name:'Unsaved house changes'}).getByRole('button',{name:'Keep editing'}).click();
    await expect(villages).toHaveValue(before);
    await editor.getByRole('button',{name:'Paint wall #487d6b'}).focus();
  }
  await page.keyboard.press('Control+z');
  await expect(preview).toHaveAttribute('data-colors',original!);
  await page.keyboard.press('Control+Shift+z');
  await expect(preview).toHaveAttribute('data-colors', /"wall":"#487d6b"/);
  await editor.getByRole('button',{name:'Beach',exact:true}).click();
  await expect(editor.getByText('Unsaved changes (2)',{exact:true})).toBeVisible();
  await page.getByRole('tab',{name:'Overview',exact:true,includeHidden:true}).dispatchEvent('click');
  const prompt = page.getByRole('dialog',{name:'Unsaved house changes'});
  await expect(prompt).toBeVisible();
  await page.screenshot({path:`artifacts/web049/leave-${width}.png`});
  await prompt.getByRole('button',{name:'Keep editing'}).click();
  await editor.getByRole('button',{name:'Undo',exact:true}).click();
  await editor.getByRole('button',{name:'Redo',exact:true}).click();
  await editor.getByText('Unsaved changes (2)',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:`artifacts/web049/exterior-${width}.png`});
  await page.keyboard.press('Escape');
  await expect(editor).toHaveCount(0);
  await expect(prompt).toHaveCount(0);
  await page.getByRole('button',{name:'Edit my house',exact:true}).click();
  await editor.getByRole('button',{name:'Modern',exact:true}).click();
  await page.getByRole('button',{name:'Close house editor',includeHidden:true}).dispatchEvent('click');
  await prompt.getByRole('button',{name:'Save',exact:true}).click();
  await expect(editor).toHaveCount(0);
  await page.getByRole('button',{name:'Edit my house',exact:true}).click();
  await expect(editor.getByRole('button',{name:'Modern',exact:true})).toHaveAttribute('aria-pressed','true');
  await expect(editor.getByRole('button',{name:'Undo',exact:true})).toBeDisabled();
  await editor.getByRole('button',{name:'Cancel house',exact:true}).click();
  const showcase = page.getByRole('region',{name:'House showcase'});
  const decorTile = showcase.locator('.showcase-tile').first();
  await decorTile.click();
  const decorPreview = page.locator('.preview-editor');
  await decorPreview.getByRole('button',{name:/^(Remove|Save) house item$/}).click();
  await expect(decorPreview).toHaveCount(0);
  await expect(showcase.getByText('Unsaved changes (1)',{exact:true})).toBeVisible();
  await showcase.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(showcase.getByText('No unsaved changes',{exact:true})).toBeVisible();
  await showcase.getByRole('button',{name:'Redo',exact:true}).click();
  await showcase.getByRole('button',{name:'Discard all',exact:true}).click();
  await page.getByRole('button',{name:'Go inside',exact:true}).click();
  const room = page.getByRole('dialog',{name:/house interior/});
  await room.getByRole('button',{name:'Decorate',exact:true}).click();
  await room.getByText('Room inventory',{exact:true}).click();
  const sofa = room.getByTestId('position-sofa');
  const observer = width === 1440 ? await context.newPage() : null;
  if (observer) {
    await observer.goto('/tests/web049-room.html');
    await observer.getByText('Room inventory',{exact:true}).click();
    await page.bringToFront();
  }
  const x = Number(await sofa.getAttribute('data-x'));
  await room.getByRole('button',{name:'Move sofa right',exact:true}).click();
  await expect(sofa).toHaveAttribute('data-x',String(x+.25));
  if (observer) await expect(observer.getByTestId('position-sofa')).toHaveAttribute('data-x',String(x));
  await room.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(sofa).toHaveAttribute('data-x',String(x));
  if (observer) await expect(observer.getByTestId('position-sofa')).toHaveAttribute('data-x',String(x));
  await page.screenshot({path:`artifacts/web049/undo-after-move-${width}.png`});
  await page.keyboard.press('Control+y');
  await expect(sofa).toHaveAttribute('data-x',String(x+.25));
  await page.keyboard.press('r');
  await expect(sofa).toHaveAttribute('data-rotation','15');
  await page.keyboard.press('Control+z');
  await expect(sofa).toHaveAttribute('data-rotation','0');
  await room.getByRole('button',{name:'Stash selected item'}).click();
  await expect(sofa).toContainText('stashed');
  await room.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(sofa).toContainText('placed');
  await room.getByRole('button',{name:'Undo',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:`artifacts/web049/interior-${width}.png`});
  await room.getByRole('button',{name:'Back to village',exact:true}).click();
  await prompt.getByRole('button',{name:'Keep editing'}).click();
  await room.getByRole('button',{name:'Discard all',exact:true}).click();
  await expect(sofa).toHaveAttribute('data-x',String(x));
  await expect(room.getByRole('button',{name:'Undo',exact:true})).toBeDisabled();
  await expect(room.getByRole('button',{name:'Redo',exact:true})).toBeDisabled();
  await room.getByRole('button',{name:'Place Armchair',exact:true}).click();
  const added = room.locator('[data-testid^="position-armchair_"]');
  await expect(added).toContainText('placed');
  await room.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(added).toContainText('stashed');
  await room.getByRole('button',{name:'Redo',exact:true}).click();
  await expect(added).toContainText('placed');
  await room.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(room.getByRole('button',{name:'Undo',exact:true})).toBeDisabled();
  if (observer) {
    const placedId = await added.getAttribute('data-testid');
    await expect(observer.getByTestId(placedId!)).toContainText('placed');
    // Persist both a forward move and its undo through the same reducer transport.
    await room.getByRole('button',{name:'Move sofa right',exact:true}).click();
    await room.getByRole('button',{name:'Undo',exact:true}).click();
    await room.getByRole('button',{name:'Save decor',exact:true}).click();
    await expect(observer.getByTestId('position-sofa')).toHaveAttribute('data-x',String(x));
  }
  await observer?.close();
  expect(await room.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
});
