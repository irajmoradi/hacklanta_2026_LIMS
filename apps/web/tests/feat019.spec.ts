import {execFileSync} from "node:child_process";
import {test, expect} from '@playwright/test';
import {useDemoSeat} from './demoSeat';
import {mockFeat019} from './feat019Mock';
useDemoSeat();
const mockOnly = process.env.VILLAGE_FEAT019_MOCK === '1';

test.beforeAll(()=>{if (process.env.FEAT019_MOCK || mockOnly) return; execFileSync("../api/.venv/bin/python", ["../api/scripts/seed_feat019_qa.py"], {stdio:"inherit"});});

const neighbor='13370000-0000-4000-8000-000000000002';
const vid='13370000-0000-4000-8000-000000000000';

test('owner edits while visitor watches; two members decorate the Hall across floors', async ({page, context}) => {
  const errors: string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  if (process.env.FEAT019_MOCK) await mockFeat019(context);
  await page.goto('/interior-preview.html');
  await expect(page.getByRole('status')).toContainText('changes saved');
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await page.getByText('Room inventory',{exact:true}).click();
  const visitor=await context.newPage();
  await visitor.goto(`/interior-preview.html?seat=${neighbor}`);
  await expect(visitor.getByRole('status')).toContainText('changes saved');
  await expect(visitor.getByRole('button',{name:'Decorate',exact:true})).toHaveCount(0);
  await visitor.getByText('Room inventory',{exact:true}).click();
  const before=Number(await page.getByTestId('position-sofa').getAttribute('data-x'));
  await page.getByRole('button',{name:'Move sofa right',exact:true}).click();
  await expect(visitor.getByTestId('position-sofa')).toHaveAttribute('data-x',String(before));
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await expect(visitor.getByTestId('position-sofa')).toHaveAttribute('data-x',String(before+.25));
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await page.screenshot({path:'artifacts/integ017/feat019/home-desktop.png'});
  await page.getByRole('tab',{name:'Floor 3',exact:true}).click();
  await page.getByRole('button',{name:'Place Armchair',exact:true}).click();
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await visitor.getByRole('tab',{name:'Floor 3',exact:true}).click();
  await expect(visitor.locator('[data-testid^="position-armchair_"]')).toHaveCount(1);
  await page.screenshot({path:'artifacts/integ017/feat019/home-floor3.png'});
  await page.goto('/interior-preview.html?hall=1');
  await visitor.goto(`/interior-preview.html?hall=1&seat=${neighbor}`);
  for(const p of [page,visitor]) {
    await expect(p.getByRole('status')).toContainText('changes saved');
    await p.getByRole('button',{name:'Decorate',exact:true}).click();
    await p.getByText('Room inventory',{exact:true}).click();
  }
  await page.getByRole('button',{name:'Decor',exact:true}).click();
  await page.getByRole('button',{name:'Place Plant Fern',exact:true}).click();
  const item=page.locator('[data-testid^="position-plant_fern_"]').first();
  await expect(item).toBeVisible();
  const id=(await item.getAttribute('data-testid'))!;
  await expect(visitor.getByTestId(id)).toHaveCount(0);
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await expect(visitor.getByTestId(id)).toBeVisible();
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  const x=Number(await item.getAttribute('data-x'));
  await visitor.getByRole('button',{name:'Move plant_fern right',exact:true}).click();
  await expect(item).toHaveAttribute('data-x',String(x));
  await expect(visitor.getByRole('button',{name:'Stash selected item'})).toBeDisabled();
  // Both members start from the same baseline; the second save must not overwrite the first.
  await page.getByRole('button',{name:'Move plant_fern right',exact:true}).click();
  await visitor.getByRole('button',{name:'Save decor',exact:true}).click();
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await expect(page.locator('.interior-error')).toContainText('shared room changed');
  await page.getByRole('button',{name:'Cancel decor',exact:true}).click();
  await expect(item).toHaveAttribute('data-x',String(x+.25));
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await visitor.getByRole('button',{name:'Decorate',exact:true}).click();
  if (!process.env.FEAT019_MOCK) {
  const denied=await page.request.post(`/api/houses/${vid}/edit?vid=${vid}`,{
    headers:{'X-Demo-User':neighbor},data:{action:'stash_item',item_id:id.slice('position-'.length),client_seq:50},
  });
  expect(denied.status()).toBe(403);
  }
  await page.getByRole('tab',{name:'Floor 2',exact:true}).click();
  await expect(item).toHaveCount(0);
  await page.getByRole('button',{name:'Place Plant Fern',exact:true}).click();
  await expect(page.locator('[data-testid^="position-plant_fern_"]')).toHaveCount(1);
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await visitor.getByRole('tab',{name:'Floor 2',exact:true}).click();
  await expect(visitor.locator('[data-testid^="position-plant_fern_"]')).toHaveCount(1);
  await visitor.getByRole('button',{name:'Furniture',exact:true}).click();
  await visitor.getByRole('button',{name:'Place Armchair',exact:true}).click();
  await visitor.getByRole('button',{name:'Save decor',exact:true}).click();
  await expect(page.locator('[data-testid^="position-armchair_"]')).toHaveCount(1);
  await page.screenshot({path:'artifacts/integ017/feat019/hall-floor2-desktop.png'});
  await page.getByRole('button',{name:'Photo objects',exact:true}).click();
  const model=page.waitForResponse(r=>r.url().includes('/api/assets/items/') && r.url().endsWith('/object.glb') && r.ok());
  await page.getByRole('button',{name:/Photo object.*By/}).click();
  await model;
  await expect(page.locator('[data-testid^="position-fe190000-"]')).toHaveCount(1);
  await expect(visitor.locator('[data-testid^="position-fe190000-"]')).toHaveCount(0);
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await page.getByRole('button',{name:/Move fe190000-.* right/}).click();
  await expect(visitor.locator('[data-testid^="position-fe190000-"]')).toHaveCount(1);
  await expect(page.getByRole('button',{name:'Stash selected item'})).toBeEnabled();
  await page.getByRole('button',{name:'Duplicate selected item'}).click();
  await expect(visitor.locator('[data-testid^="position-fe190000-"]')).toHaveCount(1);
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await expect(visitor.locator('[data-testid^="position-fe190000-"]')).toHaveCount(2);
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await page.getByRole('button',{name:/Move fe190000-.* right/}).last().click();
  await page.screenshot({path:'artifacts/integ017/feat019/hall-photo-object.png'});
  await page.getByRole('button',{name:'Stash selected item'}).click();
  await expect(page.locator('[data-testid^="position-fe190000-"]').filter({hasText:'stashed'})).toHaveCount(1);
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await page.getByRole('button',{name:'Downstairs',exact:true}).click();
  await expect(page.getByRole('tab',{name:'Ground floor'})).toHaveAttribute('aria-selected','true');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/integ017/feat019/hall-mobile.png'});
  expect(await page.locator('.interior-dialog').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await visitor.close();
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('/');
  await expect(page.getByRole('button',{name:'Community Hall',exact:true})).toBeVisible();
  await page.screenshot({path:'artifacts/integ017/feat019/town.png'});
  await page.getByRole('button',{name:'Community Hall',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Community Hall interior'})).toBeVisible();
  await page.goto('/interior-preview.html?asset=hall');
  await expect(page.getByTestId('hall-asset')).toHaveAttribute('data-ready','true');
  await page.getByTestId('hall-asset').screenshot({path:'artifacts/integ017/feat019/community-hall-asset.png'});
  expect(errors).toEqual([]);
});

test('mock Community Hall opens, decorates across floors and restores the village', async ({page}) => {
  test.skip(!mockOnly && !process.env.FEAT019_MOCK, 'Offline integration coverage');
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'Community Hall',exact:true}).click();
  const hall=page.getByRole('dialog',{name:'Community Hall interior'});
  await expect(hall).toBeVisible();
  await expect(hall.getByRole('status')).toContainText('saved on this device');
  await hall.getByRole('button',{name:'Decorate',exact:true}).click();
  await hall.getByText('Room inventory',{exact:true}).click();
  await hall.getByRole('button',{name:'Place Armchair',exact:true}).click();
  await expect(hall.locator('[data-testid^="position-armchair_"]')).toHaveCount(1);
  await hall.getByRole('tab',{name:'Floor 2',exact:true}).click();
  await expect(hall.locator('[data-testid^="position-armchair_"]')).toHaveCount(0);
  await hall.getByRole('button',{name:'Place Armchair',exact:true}).click();
  await expect(hall.locator('[data-testid^="position-armchair_"]')).toHaveCount(1);
  await page.screenshot({path:'artifacts/integ016/hall-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  expect(await hall.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
  await page.screenshot({path:'artifacts/integ016/hall-mobile.png'});
  await page.keyboard.press('Escape');
  await expect(hall.getByRole('button',{name:'Decorate',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(hall).toBeHidden();
  await expect(page.getByTestId('village-scene')).toBeVisible();
  expect(errors).toEqual([]);
});
