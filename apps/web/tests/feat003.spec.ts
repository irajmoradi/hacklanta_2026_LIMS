import { useDemoSeat } from './demoSeat';
useDemoSeat();
import { test, expect } from '@playwright/test';
import { makeFixtures } from '../src/api/fixtures';
const peer = makeFixtures().village.villagers[1];

for (const width of [1366,390]) test(`showcase detail, ownership, house target and rewards at ${width}`, async ({page}) => {
  await page.setViewportSize({width,height:width===390?844:900});
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByRole('button',{name:'My profile',exact:true}).click();
  const showcase = page.getByRole('region',{name:'Villager showcase',exact:true});
  await showcase.scrollIntoViewIfNeeded();
  await showcase.getByRole('button',{name:'Headphones',exact:true}).click();
  const detail = page.getByRole('region',{name:'Item details',exact:true});
  await expect(detail).toContainText('Shop · 120 coins');
  await expect(detail.getByRole('button',{name:'Unequip Headphones'})).toBeVisible();
  await page.screenshot({path:`tests/screenshots/FEAT-003/showcase-${width}.png`});
  await detail.scrollIntoViewIfNeeded();
  await page.screenshot({path:`tests/screenshots/FEAT-003/detail-${width}.png`});
  await detail.getByRole('button',{name:'Unequip Headphones'}).click();
  await expect(detail.getByRole('button',{name:'Equip Headphones',exact:true})).toBeVisible();
  await detail.getByRole('button',{name:'Equip Headphones',exact:true}).click();
  await expect(detail.getByRole('button',{name:'Unequip Headphones'})).toBeVisible();
  await showcase.getByText(/Earn your next signature/).click();
  await showcase.getByRole('button',{name:'Champion Mantle · How to earn'}).click();
  await expect(detail).toContainText('Earned: Weekly crown');
  await detail.scrollIntoViewIfNeeded();
  await page.screenshot({path:`tests/screenshots/FEAT-003/reward-${width}.png`});
  await expect(detail.getByRole('button',{name:/^Equip /})).toHaveCount(0);
  expect(await page.locator('.profile-panel').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.getByRole('button',{name:'Close profile'}).click();
  if (width > 700) await page.getByRole('button',{name:`Open ${peer.display_name}'s house profile`,exact:true}).click();
  else await page.getByRole('button',{name:`Visit ${peer.display_name}`,exact:true}).click();
  const house = page.getByRole('region',{name:'House showcase',exact:true});
  if (width > 700) await expect(house.getByRole('heading',{name:'House showcase'})).toBeInViewport();
  else await house.scrollIntoViewIfNeeded();
  await expect(house.locator('canvas[data-rendered="true"]')).toBeVisible();
  await page.screenshot({path:`tests/screenshots/FEAT-003/house-${width}.png`});
  await showcase.locator('button.showcase-tile').first().click();
  await expect(detail).toBeVisible();
  await expect(detail.getByRole('button',{name:/^(Equip|Unequip) /})).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('fixture-only preview and locked shop work with all generated models offline', async ({page}) => {
  await page.route('**/models/**', route => route.fulfill({status:404,body:'Offline'}));
  await page.goto('/');
  await page.getByRole('button',{name:'My profile',exact:true}).click();
  const showcase = page.getByRole('region',{name:'Villager showcase',exact:true});
  await expect(showcase.locator('canvas')).toBeVisible();
  await showcase.getByRole('button',{name:'Headphones',exact:true}).click();
  await expect(page.getByRole('region',{name:'Item details'})).toContainText('Headphones');
  await page.screenshot({path:'tests/screenshots/FEAT-003/fixture-fallback.png'});
  await page.getByRole('button',{name:'Close profile'}).click();
  await page.getByRole('button',{name:'Shop',exact:true}).click();
  const item = page.locator('.shop-item[data-item-id="champion_mantle"]');
  await expect(item).toContainText('How to earn:');
  await expect(item.getByRole('button')).toHaveCount(0);
  await item.scrollIntoViewIfNeeded();
  await page.screenshot({path:'tests/screenshots/FEAT-003/shop-rewards.png'});
});
