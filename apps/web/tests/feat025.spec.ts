import {test,expect} from '@playwright/test';
import {mockFeat019} from './feat019Mock';
const owner='13370000-0000-4000-8000-000000000001';
const neighbor='13370000-0000-4000-8000-000000000002';
test('connected cutaway: two contexts see continuous ascent and descent; floor edits preserve drafts',async({browser})=>{
  const a=await browser.newContext(),b=await browser.newContext();
  await mockFeat019([a,b]);
  const page=await a.newPage(),watch=await b.newPage();
  const errors:string[]=[];[page,watch].forEach(p=>p.on('pageerror',e=>errors.push(e.message)));
  await page.goto('/interior-preview.html?hall=1');
  await watch.goto(`/interior-preview.html?hall=1&seat=${neighbor}`);
  await expect(page.getByRole('status')).toContainText('changes saved');
  const avatar=page.getByTestId(`interior-avatar-${owner}`),peer=watch.getByTestId(`interior-avatar-${owner}`);
  await expect(avatar).toHaveAttribute('data-y','0.00');
  await page.screenshot({path:'tests/artifacts/feat025/ground-floor.png'});
  await page.getByRole('button',{name:'Upstairs'}).click();
  await expect.poll(async()=>Number(await avatar.getAttribute('data-y'))).toBeGreaterThan(.3);
  await expect.poll(async()=>Number(await peer.getAttribute('data-y'))).toBeGreaterThan(.3);
  expect(Number(await peer.getAttribute('data-y'))).toBeLessThan(3.4);
  await page.screenshot({path:'tests/artifacts/feat025/cutaway-climbing.png'});
  await expect(avatar).toHaveAttribute('data-floor','1');
  await expect(peer).toHaveAttribute('data-y','3.40');
  await expect(page.getByRole('tab',{name:'Floor 2'})).toHaveAttribute('aria-selected','true');
  await expect(page.getByRole('button',{name:'Downstairs'})).toBeVisible();
  await page.screenshot({path:'tests/artifacts/feat025/floor-2.png'});
  await page.locator('[data-interior-walk]').focus();await page.keyboard.press('e');
  await expect.poll(async()=>Number(await peer.getAttribute('data-y'))).toBeLessThan(3);
  await expect(avatar).toHaveAttribute('data-floor','0');
  await expect(avatar).toHaveAttribute('data-y','0.00');
  await page.getByRole('button',{name:'Decorate',exact:true}).click();
  await page.getByRole('button',{name:'Place Armchair',exact:true}).click();
  await page.getByRole('tab',{name:'Floor 2'}).click();
  await expect(avatar).toHaveAttribute('data-x','-3.00');
  await expect(avatar).toHaveAttribute('data-y','3.40');
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await expect(page.getByRole('tab',{name:'Ground floor'})).toHaveAttribute('aria-selected','true');
  await page.getByRole('button',{name:'Redo',exact:true}).click();
  await page.getByRole('button',{name:'Save decor',exact:true}).click();
  await watch.getByText('Room inventory',{exact:true}).click();
  await expect(watch.locator('[data-testid^="position-armchair_"]')).toHaveCount(1);
  expect(errors).toEqual([]);
  await a.close();await b.close();
});


test('three-floor private home keeps owner permissions and keyboard stair entry',async({browser})=>{
  const a=await browser.newContext(),b=await browser.newContext();
  await mockFeat019([a,b]);
  const page=await a.newPage(),visitor=await b.newPage();
  await page.goto('/interior-preview.html');
  await visitor.goto(`/interior-preview.html?seat=${neighbor}`);
  await expect(page.getByRole('button',{name:'Decorate',exact:true})).toBeVisible();
  await expect(visitor.getByRole('button',{name:'Decorate',exact:true})).toHaveCount(0);
  await page.getByRole('tab',{name:'Floor 2'}).click();
  await expect(page.getByRole('button',{name:'Downstairs'})).toBeVisible();
  await page.getByRole('button',{name:'Upstairs'}).click();
  const avatar=page.getByTestId(`interior-avatar-${owner}`);
  await expect(avatar).toHaveAttribute('data-floor','2');
  await expect(avatar).toHaveAttribute('data-y','6.80');
  await expect(visitor.getByTestId(`interior-avatar-${owner}`)).toHaveAttribute('data-y','6.80');
  await expect(page.getByRole('button',{name:'Upstairs'})).toHaveCount(0);
  await page.screenshot({path:'tests/artifacts/feat025/home-floor-3.png'});
  // Walk away from the top landing and back using keyboard alone.
  const room=page.locator('[data-interior-walk]');await room.focus();
  await page.keyboard.down('w');await page.waitForTimeout(400);await page.keyboard.up('w');
  await expect.poll(async()=>Number(await avatar.getAttribute('data-z'))).toBeLessThan(2.4);
  await page.keyboard.down('s');
  await expect.poll(async()=>Number(await avatar.getAttribute('data-y'))).toBeLessThan(6.5);
  await page.keyboard.up('s');
  await expect(avatar).toHaveAttribute('data-y','3.40');
  await a.close();await b.close();
});
