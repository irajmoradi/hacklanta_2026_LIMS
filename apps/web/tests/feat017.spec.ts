import { expect, test } from '@playwright/test';
import { MockApi, ApiError } from '../src/api/mock';
import { DEMO_USER_ID } from '../src/api/fixtures';
import { mkdirSync } from 'node:fs';

test('head speech, cache, orbit, modal reset, and consenting sequential chorus', async ({page}) => {
  const backend = new MockApi();
  const friend = '00000000-0000-4000-8000-000000000002';
  await backend.request('PATCH', '/me', friend, {allow_voice_by_friends: true});
  const requests: string[] = [], errors: string[] = [];
  let chorusMembers: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(uid => localStorage.setItem('village:seat:live', uid), DEMO_USER_ID);
  await page.route(url => url.pathname.startsWith('/api/'), async route => {
    const req = route.request(), url = new URL(req.url()), path = url.pathname.slice(4) + url.search;
    if (path.startsWith('/assets/')) return route.fulfill({json: {names: ['jawOpen'], metadata: {fps: 30}, frames: Array.from({length: 120}, (_, i) => ({weights: [.15 + .65 * Math.abs(Math.sin(i * .8))]}))}});
    try {
      const value = await backend.request<any>(req.method(), path, DEMO_USER_ID, req.postData() ? req.postDataJSON() : undefined);
      const head = (person: any) => {if (person?.avatar) person.avatar.portrait = {kind: 'lam_head', head_package_url: '/api/assets/synthetic/avatar.zip'};};
      if (value.villagers) value.villagers.forEach(head);
      if (value.villager) head(value.villager);
      if (path === '/heads/chorus') {chorusMembers = req.postDataJSON().member_ids; requests.push(path);}
      if (path.match(/^\/heads\/.+\/say$/)) {requests.push(path);value.expr_url = '/api/assets/synthetic/expr.json';}
      await route.fulfill({json: value});
    } catch (e) {await route.fulfill({status: e instanceof ApiError ? e.status : 500, json: {detail: String(e)}});}
  });
  await page.goto('/');
  await expect(page.getByRole('button', {name: 'My profile', exact: true})).toBeVisible({timeout: 20000}).catch(async () => {throw new Error(JSON.stringify({errors, body: await page.locator('body').innerText()}));});
  await page.getByRole('button', {name: 'My profile', exact: true}).click();
  const studio = page.locator('.head-studio');
  await expect(page.locator('[data-head-state="ready"]')).toBeVisible();
  await studio.getByRole('button', {name:'Who ate my sandwich?',exact:true}).click();
  await studio.getByRole('button', {name: 'Play',exact:true}).click();
  const canvas = studio.locator('canvas');
  await expect(canvas).toHaveAttribute('data-speaking', 'true');
  await expect.poll(async () => Number(await canvas.getAttribute('data-jaw'))).toBeGreaterThan(.1);
  await expect(canvas).toHaveAttribute('data-expression-frames', '120');
  mkdirSync('artifacts/feat017', {recursive: true});
  await page.screenshot({path: 'artifacts/feat017/speaking.png'});
  await expect(studio.locator('.speech-status')).toContainText('Finished');
  await studio.getByRole('button', {name: 'Play',exact:true}).click();
  await expect(canvas).toHaveAttribute('data-speaking', 'true');
  await studio.getByRole('button', {name: 'Stop', exact: true}).click();
  await expect(canvas).toHaveAttribute('data-speaking', 'false');
  await page.locator('.lam-head').filter({has:page.getByRole('button', {name:'Open big head view'})}).hover();
  await page.getByRole('button', {name: 'Open big head view'}).click();
  const stage = page.getByRole('dialog', {name: /big head view/});
  await expect(stage.locator('[data-head-state="ready"]')).toBeVisible();
  const big = stage.locator('canvas');
  await big.hover(); await page.mouse.wheel(0, -700);
  await expect.poll(async () => Number(await big.getAttribute('data-distance'))).toBeLessThan(.62);
  const box = (await big.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + 100, box.y + box.height / 2, {steps: 8}); await page.mouse.up();
  await expect.poll(async () => Math.abs(Number(await big.getAttribute('data-camera-x')))).toBeGreaterThan(.01);
  await big.dblclick();
  await expect(big).toHaveAttribute('data-distance', '0.620');
  await page.screenshot({path: 'artifacts/feat017/big-view.png'});
  await page.keyboard.press('Escape');
  await expect(stage).toHaveCount(0);
  await page.getByRole('button', {name: 'Close profile'}).click();
  await page.getByRole('button', {name: 'Everyone says it'}).click();
  const chorus = page.getByRole('dialog', {name: 'The village chorus'});
  await expect(chorus.locator('.chorus-row article')).toHaveCount(2);
  await expect(chorus.locator('.chorus-quiet > div > span')).toHaveCount(3);
  await chorus.getByRole('button', {name:'Who ate my sandwich?',exact:true}).click();
  await chorus.getByRole('button', {name: 'Everyone says it'}).click();
  await expect(chorus.locator('.speech-status')).toContainText('Finished', {timeout: 45000});
  expect(chorusMembers).toEqual([DEMO_USER_ID,friend]);
  expect(requests).toEqual([`/heads/${DEMO_USER_ID}/say`,`/heads/${DEMO_USER_ID}/say`,'/heads/chorus']);
  await page.screenshot({path: 'artifacts/feat017/chorus.png'});
  await chorus.getByRole('button', {name: 'Close dialog'}).click();
  await expect(chorus).toHaveCount(0);
  await page.setViewportSize({width: 390, height: 844});
  await page.getByRole('button', {name: 'My profile', exact: true}).click();
  await expect(page.locator('[data-head-state="ready"]')).toBeVisible();
  await page.screenshot({path: 'artifacts/feat017/mobile.png'});
  await page.locator('.lam-head').filter({has:page.getByRole('button', {name:'Open big head view'})}).hover();
  await page.getByRole('button', {name: 'Open big head view'}).click();
  await expect(stage.locator('[data-head-state="ready"]')).toBeVisible();
  const touchBox = (await big.boundingBox())!, x = touchBox.x + touchBox.width / 2, y = touchBox.y + touchBox.height / 2;
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', {type: 'touchStart', touchPoints: [{x:x-35,y,id:1},{x:x+35,y,id:2}]});
  await cdp.send('Input.dispatchTouchEvent', {type: 'touchMove', touchPoints: [{x:x-70,y,id:1},{x:x+70,y,id:2}]});
  await cdp.send('Input.dispatchTouchEvent', {type: 'touchEnd', touchPoints: []});
  await expect.poll(async () => Number(await big.getAttribute('data-distance'))).toBeLessThan(.62);
  expect(Number(await big.getAttribute('data-distance'))).toBeGreaterThanOrEqual(.22);
  await stage.getByRole('button', {name: 'Close big head view'}).click();
  await expect(page.getByRole('button', {name: 'Close profile'})).toBeVisible();
  expect(errors).toEqual([]);
});
