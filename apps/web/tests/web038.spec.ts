test('purchase failure keeps the draft; color failure reports the successful purchase separately',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:'Shop',exact:true}).click();
  await page.locator('[data-item-id="hat_beanie"]').getByRole('button',{name:/Try on/}).click();
  await page.getByRole('button',{name:'Woodland',exact:true}).click();
  await page.evaluate(async()=>{const {api}=await import('/src/api/client.ts' as string);const buy=api.buy;api.buy=async(...args:unknown[])=>{api.buy=buy;throw new Error('Purchase unavailable');};});
  await page.locator('.try-on-pane').getByRole('button',{name:/^Buy/}).click();
  await expect(page.locator('.form-error[role=alert]')).toContainText('Purchase unavailable');
  await expect(page.getByTestId('shop-balance')).toHaveText('420');
  await expect(page.locator('.try-on-pane')).toBeVisible();
  await page.evaluate(async()=>{const {api}=await import('/src/api/client.ts' as string);api.itemColors=async()=>{throw new Error('Color service unavailable');};});
  await page.locator('.try-on-pane').getByRole('button',{name:/^Buy/}).click();
  await expect(page.locator('.form-error[role=alert]')).toContainText('Purchased and equipped, but colors could not save');
  await expect(page.getByTestId('shop-balance')).toHaveText('390');
  await expect(page.locator('[data-item-id="hat_beanie"]')).toContainText('Equipped');
  await expect(page.locator('.try-on-pane')).toHaveCount(0);
});
