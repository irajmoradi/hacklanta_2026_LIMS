test('try colors without saving, buy and equip, then preview pets and house', async ({page}) => {
  const errors:string[]=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('/'); await page.getByRole('button',{name:'Shop',exact:true}).click();
  const card=page.locator('[data-item-id="hat_beanie"]');
  await card.getByRole('button',{name:'Try on Cozy Beanie',exact:true}).click();
  const pane=page.getByRole('region',{name:'Try on Cozy Beanie',exact:true});
  await expect(pane.getByRole('heading')).toBeFocused();
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).previewHas('hat_beanie'))).toBe(true);
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).shopPreview().mirror)).toBe(true);
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).shopPreview().x)).toBeGreaterThan(3.8);
  await pane.getByRole('button',{name:'Woodland',exact:true}).click();
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).previewColors('hat_beanie'))).toContain('#689b68');
  await expect(page.getByTestId('shop-balance')).toHaveText('420');
  await mkdir('artifacts/web038',{recursive:true});
  await page.screenshot({path:'artifacts/web038/clothing-mirror.png'});
  await pane.getByRole('button',{name:'Done',exact:true}).click();
  await expect(card.getByRole('button',{name:'Try on Cozy Beanie',exact:true})).toBeFocused();
  await expect(card).not.toContainText('Equipped');
  await card.getByRole('button',{name:'Try on Cozy Beanie',exact:true}).press('Enter');
  await pane.getByRole('button',{name:'Twilight',exact:true}).click();
  await pane.getByRole('button',{name:/^Buy/}).click();
  await expect(pane).toHaveCount(0); await expect(card).toContainText('Equipped');
  await expect(page.getByTestId('shop-balance')).toHaveText('390');
  await expect(card.getByRole('button',{name:/Try on/})).toBeFocused();
  const equipped = await page.evaluate(async()=>{const {api}=await import('/src/api/client.ts' as string);const me=await api.me();const p=await api.profile(me.villages[0].id,api.user);return p.villager.equipped.find((i:{item_id:string})=>i.item_id==='hat_beanie');});
  expect(equipped.colors.primary).toBe('#557ca7');
  await page.getByRole('tab',{name:'Farm Store',exact:true}).click();
  await page.getByRole('button',{name:'Try on Tabby Cat',exact:true}).click();
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).shopPreview().pet)).toBe(true);
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).previewHas('pet_cat_tabby'))).toBe(true);
  await page.screenshot({path:'artifacts/web038/pet-store.png'});
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.locator('[data-item-id="house_paddock"]').getByRole('button',{name:/Try on/}).click();
  await expect(page.locator('.try-on-pane [role="img"]')).toHaveAttribute('aria-label',/^House/);
  await expect.poll(()=>page.evaluate(async()=> (await import('/tests/web038Scene.ts' as string)).previewHas('house_paddock'))).toBe(true);
  await page.screenshot({path:'artifacts/web038/house-paddock.png'});
  await page.getByRole('button',{name:'Done',exact:true}).click();
  await page.getByRole('tab',{name:'Village Shop',exact:true}).click();
  await expect(page.locator('[data-item-id="revival_potion"] [data-try-on]')).toHaveCount(0);
  expect(errors).toEqual([]);
});

