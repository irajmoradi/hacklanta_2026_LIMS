import { test, expect } from '@playwright/test';
import { useDemoSeat } from './demoSeat';
useDemoSeat();

test('complete base, go beyond, share tier progress, finish and receive bonus', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'My goal', exact: true }).click();
  await page.getByRole('button', { name: 'Mark goal done', exact: true }).click();
  await expect(page.getByRole('button', { name: '🚀 Go beyond', exact: true })).toBeVisible();
  await page.getByLabel('Stretch target (optional)').fill('Run five times');
  await page.getByRole('button', { name: '🚀 Go beyond', exact: true }).click();
  await expect(page.getByLabel('Goal journey')).toContainText('Stretch 1: Run five times');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Check in', exact: true }).click();
  await page.getByRole('button', { name: /Goal progress/ }).click();
  await expect(page.getByRole('dialog')).toContainText('Stretch 1: Run five times');
  await page.getByRole('textbox').fill('Completed the fourth run by the lake');
  await page.getByRole('button', { name: /Share check-in/ }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'My goal', exact: true }).click();
  await expect(page.getByLabel('Goal journey')).toContainText('1 progress check-ins');
  await page.getByRole('button', { name: /Finish stretch 1/ }).click();
  await expect(page.getByLabel('Goal journey')).toContainText('Above & beyond');
  await expect(page.getByLabel('Goal journey')).toContainText('+10 XP and 10 coins');
  await expect(page.getByRole('progressbar', { name: 'Stretch 1 progress' })).toHaveAttribute('value', '2');
  await page.screenshot({ path: 'tests/screenshots/FEAT-018/stretch-complete.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'tests/screenshots/FEAT-018/stretch-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Check in', exact: true }).click();
  await expect(page.getByRole('button', { name: /Goal progress/ })).toBeDisabled();
  await page.getByRole('button', { name: '🚀 Go beyond', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'My goal', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'My profile', exact: true }).click();
  await page.getByRole('tab', { name: 'Activity', exact: true }).click();
  await expect(page.getByLabel('Personal activity')).toContainText('went above & beyond');
  await page.screenshot({ path: 'tests/screenshots/FEAT-018/stretch-feed.png' });
});
