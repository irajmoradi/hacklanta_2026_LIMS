import {test,expect} from '@playwright/test';
import {useDemoSeat} from './demoSeat';
useDemoSeat();
for(const width of [1440,390])test(`Treasury and payout terms at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:/^Shop/}).click();
 await page.locator('summary').filter({hasText:'Treasury'}).click();
 await expect(page.getByRole('region',{name:'Treasury',exact:true})).toContainText('1,000 XP');
 await page.getByRole('button',{name:'Convert SOL to XP'}).click();
 await expect(page.getByText(/No compatible wallet installed/)).toBeVisible();
 await page.getByText(/No compatible wallet installed/).scrollIntoViewIfNeeded();
 await page.screenshot({path:`tests/screenshots/FEAT-027-treasury-${width}.png`});
 await page.getByRole('button',{name:'Back to town',exact:true}).click();
 await page.getByRole('button',{name:'Compete',exact:true}).click();
 await page.getByRole('button',{name:/\+ Create/}).click();
 await page.getByLabel('Competition title').fill('Devnet ranked challenge');
 await page.getByLabel('Terms',{exact:true}).fill('Confirmed study progress; earlier joins break ties.');
 await page.getByLabel('Payout mode').selectOption('ranked');
 await page.getByLabel('Ranked percentages').fill('60/30');
 await expect(page.getByRole('button',{name:'Create competition with these terms'})).toBeDisabled();
 await page.getByLabel('Ranked percentages').fill('60/30/10');
 await page.getByLabel('Devnet SOL entry').fill('0.01');
 await page.getByLabel('Entry deadline').fill('2027-01-01T12:00');
 await expect(page.getByText(/Projected payouts with 3 entrants/)).toContainText('0.018 / 0.009 / 0.003');
 await page.getByRole('button',{name:'Create competition with these terms'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:`tests/screenshots/FEAT-027-create-${width}.png`});
 await page.getByRole('button',{name:'Create competition with these terms'}).click();
 await page.getByRole('button',{name:'Open',exact:true}).click();
 await page.mouse.move(width-1,899);
 await expect(page.getByRole('region',{name:'Payout terms',exact:true})).toBeVisible();
 await page.getByRole('region',{name:'Payout terms',exact:true}).scrollIntoViewIfNeeded();
 await expect(page.getByRole('region',{name:'Payout terms',exact:true})).toContainText('60 / 30 / 10');
 await expect(page.getByText(/Creator must create and confirm/)).toBeVisible();
 await page.waitForTimeout(250); // Finish the panel's 180 ms opening animation before visual QA.
 await page.screenshot({path:`tests/screenshots/FEAT-027-competition-${width}.png`});
 expect(errors).toEqual([]);
});
