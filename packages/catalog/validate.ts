import Ajv2020 from 'ajv/dist/2020';
import { compile } from 'json-schema-to-typescript';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import schema from './catalog.schema.json';
import type { VillageCatalog } from './dist/catalog';

const directory = import.meta.dir;
const models = process.env.VILLAGE_CATALOG_MODEL_DIR ?? join(directory, '../../apps/web/public/models');
const checkSchema = new Ajv2020({ allErrors: true, strict: false }).compile(schema);
export async function validate(data: unknown, modelDirectory = models): Promise<VillageCatalog> {
  if (!checkSchema(data)) throw new Error(JSON.stringify(checkSchema.errors));
  // Reject the common UTF-8-as-cp1252/latin1 signatures, including double encoding.
  if (/[\u00c3\u00c2][\u0080-\u00bf]|\u00e2[\u0080\u20ac]|\ufffd/.test(JSON.stringify(data))) throw new Error('Catalog contains mojibake');
  const catalog = data as VillageCatalog;
  const fail = (message: string): never => { throw new Error(message); };
  const unique = (ids: string[]) => {
    if (new Set(ids).size !== ids.length) fail('Duplicate IDs');
  };
  unique(catalog.entries.map(e => e.id));
  unique(catalog.buildings.map(b => b.id));
  unique(catalog.districts.map(d => d.id));
  unique((catalog.event_packs ?? []).map(p => p.id));
  const byId = new Map(catalog.entries.map(e => [e.id, e]));
  for (const pack of catalog.event_packs ?? []) {
    for (const id of pack.pieces) {
      const entry = byId.get(id);
      if (entry?.kind !== 'decoration' || !entry.tags?.includes('event_pack')) fail(`Invalid event pack piece: ${id}`);
    }
  }
  const buildingIds = new Set(catalog.buildings.map(b => b.id));
  const unlocked = new Set<string>();
  catalog.levels.forEach((level, index) => {
    if (level.level !== index + 1 || (index === 0 ? level.xp !== 0 : level.xp <= catalog.levels[index - 1].xp)) fail('Levels must be consecutive with increasing XP starting at zero');
    for (const id of level.buildings) {
      if (!buildingIds.has(id) || unlocked.has(id) || byId.get(id)?.unlock?.village_level !== level.level) fail(`Invalid building unlock: ${id}`);
      unlocked.add(id);
    }
  });
  for (const building of catalog.buildings) {
    if (byId.get(building.id)?.kind !== 'building' || !unlocked.has(building.id)) fail(`Invalid building: ${building.id}`);
    if (!catalog.districts.some(d => d.id === building.placement.district)) fail('Unknown district');
  }
  const referenced = new Set<string>();
  for (const entry of catalog.entries) {
    const slots = entry.kind === 'clothing' ? ['head', 'face', 'torso', 'neck', 'bottoms', 'shoes'] : entry.kind === 'building' ? [] : [entry.kind];
    if (entry.kind === 'building' ? entry.slot !== undefined || (!buildingIds.has(entry.id) && !entry.tags?.includes('separate_scene')) : !slots.includes(entry.slot ?? '')) fail(`Invalid slot: ${entry.id}`);
    if ((entry.kind === 'voice_style') !== Boolean(entry.voice_style)) fail(`Invalid voice style: ${entry.id}`);
    if (entry.tags?.includes('separate_scene') && (entry.kind !== 'building' || entry.unlock || buildingIds.has(entry.id))) fail('Separate scene buildings cannot have town progression');
    if (entry.kind === 'building' && entry.tags?.includes('shop')) fail('Buildings cannot be shop items');
    if (entry.unlock && entry.unlock.village_level > catalog.levels.length) fail('Unknown level');
    for (const id of entry.requires ?? []) if (!byId.has(id)) fail(`Unknown requirement: ${id}`);
    if (entry.asset) {
      if (entry.asset.variants) {
        unique(entry.asset.variants.map(v => v.id));
        for (const variant of entry.asset.variants) {
          if (Object.keys(variant.materials).some(key => !entry.asset?.tint_materials?.includes(key))) fail(`Unknown variant material: ${entry.id}`);
        }
      }
      const filename = entry.asset.glb.slice('/models/'.length);
      if (!await Bun.file(join(modelDirectory, filename)).exists()) fail(`Missing GLB: ${filename}`);
      referenced.add(filename);
    }
    if (entry.scatter && (!entry.tags?.includes('nature') || entry.kind !== 'decoration' || !entry.asset)) fail(`Invalid scatter entry: ${entry.id}`);
  }
  const visiting = new Set<string>(), visited = new Set<string>();
  function visit(id: string) {
    if (visiting.has(id)) fail(`Requirement cycle: ${id}`);
    if (visited.has(id)) return;
    visiting.add(id);
    for (const dep of byId.get(id)!.requires ?? []) visit(dep);
    visiting.delete(id); visited.add(id);
  }
  for (const id of byId.keys()) visit(id);
  // Parallel art packs may precede catalog rollout; validate every referenced asset.
  return catalog;
}

if (import.meta.main) {
  try {
    const catalog = await validate(await Bun.file(join(directory, 'catalog.json')).json());
    const types = await compile(schema as any, 'VillageCatalog', { bannerComment: '/* Generated by bun run validate. Do not edit. */' });
    await mkdir(join(directory, 'dist'), { recursive: true });
    await Bun.write(join(directory, 'dist/catalog.ts'), types + '\nimport { legacyClientCatalog } from "../legacyClientCatalog";\nexport const catalogData: VillageCatalog = ' + JSON.stringify(catalog, null, 2) + ';\nexport const catalog = legacyClientCatalog(catalogData);\nexport const entriesById = new Map(catalogData.entries.map(entry => [entry.id, entry]));\n');
    console.log(`Validated ${catalog.entries.length} entries; generated dist/catalog.ts`);
  } catch (error) { console.error(String(error)); process.exitCode = 1; }
}
